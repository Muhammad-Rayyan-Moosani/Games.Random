import { getEditor } from './editor.js';

/**
 * Copy current code to clipboard
 * Shows visual feedback on the button
 * 
 * @param {Event} event - Click event from copy button
 */
export function copyCode(event) {
    const editor = getEditor();
    if (!editor) {
        console.error('Editor not initialized');
        return;
    }

    navigator.clipboard.writeText(editor.getValue()).then(() => {
        const btn = event ? event.target : document.querySelector('[onclick*="copyCode"]');
        if (btn) {
            const originalText = btn.textContent;
            btn.textContent = '✓';
            setTimeout(() => btn.textContent = originalText, 2000);
        }
        console.log('✅ Code copied to clipboard');
    }).catch(err => {
        console.error('Failed to copy code:', err);
    });
}

/**
 * Download game code as a JavaScript file
 * Creates a .js file with timestamp
 */
export function downloadCode() {
    const editor = getEditor();
    if (!editor) {
        console.error('Editor not initialized');
        return;
    }

    const code = editor.getValue();
    const library = window.gameState?.library || 'game';
    
    const blob = new Blob([code], { type: 'text/javascript' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `game-${library}-${Date.now()}.js`;
    a.click();
    URL.revokeObjectURL(url);

    // Close download menu
    closeDownloadMenu();
    
    console.log('✅ JavaScript file downloaded');
}

/**
 * Download game as standalone HTML file
 * Creates a complete, self-contained HTML file ready to share
 */
export function downloadStandaloneHTML() {
    const editor = getEditor();
    if (!editor) {
        console.error('Editor not initialized');
        return;
    }

    const code = editor.getValue();
    const library = window.gameState?.library || 'game';

    // Generate complete standalone HTML
    const standaloneHTML = generateStandaloneHTML(code, library);

    // Create download
    const blob = new Blob([standaloneHTML], { type: 'text/html' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `game-${library}-${Date.now()}.html`;
    a.click();
    URL.revokeObjectURL(url);

    // Close download menu
    closeDownloadMenu();

    console.log('✅ Standalone HTML downloaded!');
}

/**
 * Generate standalone HTML file with embedded game code
 * Creates a complete, self-contained HTML document
 * 
 * @param {string} gameCode - JavaScript game code to embed
 * @param {string} library - Game library ('p5js' or 'phaser')
 * @returns {string} Complete HTML document as string
 */
function generateStandaloneHTML(gameCode, library) {
    const isP5js = library === 'p5js';
    const libraryScript = isP5js
        ? '<script src="https://cdnjs.cloudflare.com/ajax/libs/p5.js/1.7.0/p5.min.js"><\/script>'
        : '<script src="https://cdnjs.cloudflare.com/ajax/libs/phaser/3.60.0/phaser.min.js"><\/script>';

    return `<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>Game - Generated by games.random</title>
    ${libraryScript}
    <style>
        * {
            margin: 0;
            padding: 0;
            box-sizing: border-box;
        }
        body {
            background: #0a0a0a;
            display: flex;
            flex-direction: column;
            justify-content: center;
            align-items: center;
            min-height: 100vh;
            font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', sans-serif;
            color: #e0e0e0;
            padding: 20px;
        }
        #game-container {
            background: #1a1a1a;
            border-radius: 8px;
            padding: 20px;
            box-shadow: 0 8px 32px rgba(0, 0, 0, 0.5);
            position: relative;
        }
        .watermark {
            text-align: center;
            margin-top: 15px;
            padding: 10px;
            font-size: 0.85em;
            color: #666;
            position: relative;
            z-index: 1000;
            background: #1a1a1a;
            border-radius: 4px;
        }
        .watermark a {
            color: #00ff88;
            text-decoration: none;
            font-weight: 500;
        }
        .watermark a:hover {
            text-decoration: underline;
        }
        /* Ensure game canvas doesn't overlap watermark */
        canvas {
            display: block;
            margin: 0 auto;
        }
    </style>
</head>
<body>
    <div id="game-container">
        <div id="game"></div>
    </div>
    <div class="watermark">
        Generated by <a href="https://github.com/yourusername/games-random" target="_blank">games.random</a>
    </div>

    <script>
${gameCode}
    <\/script>
</body>
</html>`;
}

/**
 * Toggle download menu dropdown visibility
 * 
 * @param {Event} event - Click event from download button
 */
export function toggleDownloadMenu(event) {
    if (event) {
        event.stopPropagation();
    }
    
    const menu = document.getElementById('downloadMenu');
    if (!menu) {
        console.error('Download menu not found');
        return;
    }

    menu.style.display = menu.style.display === 'none' ? 'block' : 'none';
}

/**
 * Close download menu
 * Helper function to hide the dropdown
 */
function closeDownloadMenu() {
    const menu = document.getElementById('downloadMenu');
    if (menu) {
        menu.style.display = 'none';
    }
}

